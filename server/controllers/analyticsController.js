const PDFDocument = require('pdfkit');
const analyticsService = require('../services/analyticsService');

async function exportCsv(req, res) {
  const report = await analyticsService.getMonthlyAnalytics(req.query.month);
  const csv = analyticsService.toCsv(report);

  res.setHeader('Content-Type', 'text/csv; charset=utf-8');
  res.setHeader(
    'Content-Disposition',
    `attachment; filename="platform-analytics-${report.month}.csv"`,
  );

  res.status(200).send(csv);
}

async function exportPdf(req, res) {
  const report = await analyticsService.getMonthlyAnalytics(req.query.month);

  const doc = new PDFDocument({ margin: 50 });
  const chunks = [];

  doc.on('data', (chunk) => chunks.push(chunk));
  doc.on('end', () => {
    const pdf = Buffer.concat(chunks);

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader(
      'Content-Disposition',
      `attachment; filename="platform-analytics-${report.month}.pdf"`,
    );

    res.status(200).send(pdf);
  });

  doc.fontSize(20).text('Monthly Platform Analytics', { align: 'center' });
  doc.moveDown();
  doc.fontSize(12).text(`Month: ${report.month}`);
  doc.moveDown();

  const metrics = [
    ['Orders', report.orders],
    ['GMV', report.gmv],
    ['Platform Commission', report.platformCommission],
    ['Average Order Value (AOV)', report.averageOrderValue],
    ['New Users', report.newUsers],
  ];

  metrics.forEach(([label, value]) => {
    doc.font('Helvetica-Bold').text(`${label}: `, { continued: true });
    doc.font('Helvetica').text(String(value));
    doc.moveDown(0.5);
  });

  doc.moveDown();
  doc.fontSize(9).fillColor('gray').text(
    'Generated by the Online Bookstore platform.',
  );

  doc.end();
}

module.exports = { exportCsv, exportPdf };